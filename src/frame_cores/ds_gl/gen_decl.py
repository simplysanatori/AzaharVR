#!/usr/bin/env python3
# gen_decl.py MELONDS_SRC OUT_DIR [FILES...]: writes ds_gl_decl.h, the OpenGL declarations melonDS's renderer uses (from its glad.h, itself generated from the Khronos registry), and ds_gl_list.inc for a pass-through harness
import re, sys, os
src, out = sys.argv[1], sys.argv[2]
files = ["GPU_OpenGL.cpp","GPU_OpenGL.h","GPU2D_OpenGL.cpp","GPU2D_OpenGL.h","GPU3D_OpenGL.cpp","GPU3D_OpenGL.h",
         "GPU3D_TexcacheOpenGL.cpp","GPU3D_TexcacheOpenGL.h","OpenGLSupport.cpp","OpenGLSupport.h","GPU3D_Compute.cpp","GPU3D_Compute.h"]
text = "".join(open(os.path.join(src, f)).read() for f in files)
core = "".join(open(os.path.join(src, f)).read() for f in files[:10])
glad = open(os.path.join(src, "frontend/glad/glad.h")).read()
protos = {}
for m in re.finditer(r"typedef (.+?) \(APIENTRYP PFNGL(\w+)PROC\)\((.*?)\);", glad):
    protos[m.group(2)] = (m.group(1).strip(), m.group(3).strip())
names = {}
for m in re.finditer(r"#define (gl\w+) glad_(gl\w+)", glad):
    names[m.group(1).upper()[2:]] = m.group(1)
used = sorted(set(re.findall(r"\b(gl[A-Z]\w+)\b", text)))
usedcore = set(re.findall(r"\b(gl[A-Z]\w+)\b", core))
extra = "".join(open(f).read() for f in sys.argv[3:])
consts = sorted(set(re.findall(r"\b(GL_[A-Z0-9_]+[A-Za-z0-9_]*)\b", text + extra)))
defs = dict(re.findall(r"#define (GL_\w+) (0x[0-9A-Fa-f]+|\d+)\b", glad))
h = ["// Generated by gen.py from melonDS's glad.h: the OpenGL declarations its renderer uses.", "#pragma once",
     "#include <cstddef>", "#include <cstdint>",
     "typedef unsigned int GLenum; typedef unsigned char GLboolean; typedef unsigned int GLbitfield;",
     "typedef void GLvoid; typedef int GLint; typedef unsigned int GLuint; typedef int GLsizei;",
     "typedef float GLfloat; typedef double GLdouble; typedef char GLchar; typedef std::ptrdiff_t GLintptr;",
     "typedef std::ptrdiff_t GLsizeiptr; typedef float GLclampf; typedef double GLclampd; typedef unsigned char GLubyte;",
     "typedef void (*GLDEBUGPROC)(GLenum, GLenum, GLuint, GLenum, GLsizei, const GLchar*, const void*);", ""]
for c in consts:
    if c in defs: h.append(f"#define {c} {defs[c]}")
    else: print("no const", c, file=sys.stderr)
h.append("")
table = []
for u in used:
    key = u.upper()[2:]
    if key not in protos:
        print("no proto", u, file=sys.stderr); continue
    ret, args = protos[key]
    h.append(f"{ret} {u}({args});")
    table.append((u, ret, args, u in usedcore))
open(os.path.join(out, "ds_gl_decl.h"), "w").write("\n".join(h) + "\n")
# list for the backends: X(name, ret, (args), (argnames), core)
x = []
for u, ret, args, c in table:
    an = [] if args in ("void", "") else [re.sub(r".*[ \*]", "", a.strip()) for a in args.split(",")]
    x.append(f"X({u}, {ret}, ({args}), ({', '.join(an)}), {int(c)})")
open(os.path.join(out, "ds_gl_list.inc"), "w").write("\n".join(x) + "\n")
print(len(table), "functions,", sum(1 for t in table if t[3]), "in the renderer proper;", len(consts), "constants")
