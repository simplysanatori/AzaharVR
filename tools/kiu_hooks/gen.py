#!/usr/bin/env python3
"""Assemble stubs.s (with stubs-eur.inc) and print src/frame_xr/input/kiu_hooks_stubs.h.
Needs llvm-mc, llvm-objcopy, llvm-objdump and llvm-nm. Called by gen.sh and check.sh."""
import os
import re
import struct
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))


def run(*cmd):
    return subprocess.run(cmd, check=True, capture_output=True, text=True).stdout


def equs(path):
    out = {}
    for line in open(path):
        m = re.match(r"\s*\.equ\s+(\w+),\s*(0x[0-9A-Fa-f]+|\d+)\s*(?:@\s*(.*))?$", line)
        if m:
            out[m.group(1)] = (int(m.group(2), 0), (m.group(3) or "").strip())
    return out


def main():
    src = open(os.path.join(HERE, "stubs-eur.inc")).read() + open(os.path.join(HERE, "stubs.s")).read()
    with tempfile.TemporaryDirectory() as tmp:
        s, o, b = (os.path.join(tmp, n) for n in ("stubs.s", "stubs.o", "stubs.bin"))
        open(s, "w").write(src)
        run("llvm-mc", "-triple=armv6k-none-eabi", "-mattr=+vfp2", "-filetype=obj", "-o", o, s)
        if "RELOCATION RECORDS" in run("llvm-objdump", "-r", o):
            sys.exit("stubs.s needs relocations: every outside address must be a literal")
        run("llvm-objcopy", "-O", "binary", "-j", ".text", o, b)
        image = open(b, "rb").read()
        dis = run("llvm-objdump", "-d", "--no-show-raw-insn", "--no-print-imm-hex", o)
        syms = {}
        for line in run("llvm-nm", o).splitlines():
            f = line.split()
            if len(f) == 3 and f[1] in "tT":  # labels in the image, not the .equ constants
                syms[f[2]] = int(f[0], 16)
    if len(image) % 4:
        sys.exit("the image is not whole words")
    words = struct.unpack("<%dI" % (len(image) // 4), image)
    text = {}
    for line in dis.splitlines():
        m = re.match(r"\s*([0-9a-f]+):\s+(.*)$", line)
        if m:
            t = re.sub(r"\s+", " ", m.group(2).split("@")[0]).strip()
            text[int(m.group(1), 16)] = re.sub(r" <[^>]*>", "", t)
    labels = {v: k for k, v in syms.items()}
    eur = equs(os.path.join(HERE, "stubs-eur.inc"))
    eq = equs(os.path.join(HERE, "stubs.s"))

    def camel(name):
        return "".join(p.capitalize() for p in name.lower().split("_"))

    p = print
    p("// Copyright 2026 AzaharFrame contributors")
    p("// Licensed under GPLv3 or any later version")
    p("// Refer to the license.txt file included.")
    p()
    p("// AzaharFrame kiuhook: the stubs' machine words, GENERATED by tools/kiu_hooks/gen.sh from")
    p("// tools/kiu_hooks/stubs.s (the ARM source, with what each stub does and keeps) and")
    p("// stubs-eur.inc. Do not edit: change the source, run gen.sh; tools/kiu_hooks/check.sh")
    p("// assembles it again, compares, and runs the stubs under qemu-arm. Each word's comment is")
    p("// its offset in the image and its instruction.")
    p()
    p("#pragma once")
    p()
    p("#include <array>")
    p("#include <cstdint>")
    p()
    p("namespace FrameXr::Input::KiuHooks::Stubs {")
    p()
    p("// What the image's literals name (EUR original code).")
    for name, (value, note) in eur.items():
        if name != "IMAGE_VERSION":
            p(f"inline constexpr uint32_t k{camel(name)} = 0x{value:08X};" + (f" ///< {note}" if note else ""))
    p()
    p(f"inline constexpr uint32_t kImageVersion = {eur['IMAGE_VERSION'][0]};")
    p(f"inline constexpr uint32_t kImageTag = 0x{words[0]:08X}; ///< \"KIUH\", the image's first word")
    p("// Offsets in the image: the stubs' entries and the literals.")
    for name in ("eye_stub", "shot_stub", "lit_mailbox", "lit_actor_vtable", "lit_sink_continue",
                 "lit_spawn", "lit_no_target"):
        p(f"inline constexpr uint32_t k{camel(name)} = 0x{syms[name]:03X};")
    p()
    p("// The mailbox: offsets from its base, and the flags.")
    for name, (value, note) in eq.items():
        if name.startswith("MB_") or name.startswith(("EYE_", "SHOT_")) and name != "SHOT_SAVED":
            p(f"inline constexpr uint32_t k{camel(name)} = 0x{value:02X};" + (f" ///< {note}" if note else ""))
    p()
    p(f"inline constexpr std::array<uint32_t, {len(words)}> kImage{{{{")
    for i, w in enumerate(words):
        off = i * 4
        if off == 0:
            note = '"KIUH"'
        elif off == 4:
            note = "the image's version"
        else:
            note = re.sub(r"^(?:[0-9a-f]{2} )+(?=\.word)", "", text.get(off, "?"))
        if off in labels and off >= 8:
            note = f"{labels[off]}: {note}"
        p(f"    0x{w:08X}, // {off:03X} {note}")
    p("}};")
    p()
    p("} // namespace FrameXr::Input::KiuHooks::Stubs")


if __name__ == "__main__":
    main()
